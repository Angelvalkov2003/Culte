import type { Metadata } from "next";
import Link from "next/link";
import { LEGAL_UPDATED, LegalPage } from "@/components/site/legal-page";
import { companyInfo, getSettings } from "@/lib/settings";
import { getShippingMethods } from "@/lib/shop/catalog";
import { formatEUR } from "@/lib/format";

export const dynamic = "force-dynamic";
export const metadata: Metadata = {
  title: "Доставка и връщане",
  description: "Начини и цени на доставка, 14-дневно право на отказ и връщане на продукти от Culte.",
  alternates: { canonical: "/shipping-returns" },
};

export default async function ShippingReturnsPage() {
  const [methods, s] = await Promise.all([getShippingMethods(), getSettings()]);
  const c = companyInfo(s);
  return (
    <LegalPage title="Доставка и връщане" updated={LEGAL_UPDATED} incomplete={!c.complete}>
      <h2>Доставка</h2>
      {methods.length > 0 ? (
        <ul>
          {methods.map((m) => (
            <li key={m.id}>
              <strong>{m.name}</strong> — {Number(m.price) === 0 ? "безплатна" : formatEUR(m.price)}
              {m.free_over != null && Number(m.price) > 0 && `, безплатна при поръчка над ${formatEUR(m.free_over)}`}.
              {m.description && ` ${m.description}`}
            </li>
          ))}
        </ul>
      ) : (
        <p>Доставяме в цяла България до адрес или офис на куриер.</p>
      )}
      <p>
        Поръчките се обработват до 1 работен ден и се доставят обикновено за 1–3 работни дни, но не по-късно от 30 дни от
        поръчката. Ако трябва да уточним нещо, ще ви се обадим. При наложен платеж плащате на куриера при получаване.
      </p>

      <h2>Право на отказ в 14 дни</h2>
      <p>
        Можете да се откажете от покупката без да посочвате причина в срок от 14 дни от деня, в който вие (или посочено от вас
        лице, различно от куриера) получите продуктите.
      </p>
      <p>Как да заявите отказ — по който и да е от начините:</p>
      <ul>
        <li>
          онлайн: <Link href="/withdrawal" className="link-underline">Отказ от договора тук</Link> — на екрана веднага виждате
          номера и часа на заявлението;
        </li>
        <li>по имейл на {c.email}, със стандартния формуляр или свободен текст;</li>
        <li>по телефона на {c.phone}.</li>
      </ul>
      <p>Достатъчно е да изпратите изявлението преди изтичането на 14-дневния срок.</p>

      <h2>Връщане на продуктите и на сумата</h2>
      <ul>
        <li>Изпратете продуктите до 14 дни от изявлението за отказ на адреса, който ще ви посочим.</li>
        <li>Разходите за обратната доставка са за ваша сметка, освен ако продуктът е дефектен или сме изпратили грешен продукт.</li>
        <li>
          Връщаме всички получени суми, включително стандартната доставка, до 14 дни от получаването на отказа, по същия
          начин, по който сте платили. Можем да задържим плащането, докато получим продуктите или доказателство, че са
          изпратени.
        </li>
        <li>Отговаряте за намалената стойност на продуктите, ако сте ги използвали повече от необходимото, за да ги разгледате.</li>
      </ul>

      <h2>Изключения</h2>
      <p>
        Запечатани козметични продукти (шампоани, балсами, парфюми, лосиони), които са отворени след доставката, не могат да
        бъдат върнати поради хигиенни причини (чл. 57, т. 5 ЗЗП). Неотворените продукти могат да бъдат върнати.
      </p>

      <h2>Дефектни или несъответстващи продукти</h2>
      <p>
        Ако продуктът е повреден, различен от поръчания или не отговаря на описанието, свържете се с нас на {c.email}. Имате
        право на безплатен ремонт или замяна, а ако това не е възможно — на намаляване на цената или връщане на сумата.
        Отговаряме за липса на съответствие, проявила се до 2 години след доставката.
      </p>
    </LegalPage>
  );
}
